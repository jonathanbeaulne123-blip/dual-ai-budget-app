/** Generate the shared library landing from its authored contour and the native ground.
 * Expensive terrain constraints run here, never while the browser opens the world. */
import {createServer} from 'vite';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {gunzipSync} from 'node:zlib';
import {resolve} from 'node:path';
import {generateLibraryLanding} from './horizon/library-landing-solver.mjs';
import {awningReturnInput} from './horizon/awning-return-input.mjs';
import {generateAwningReturn} from './horizon/awning-return-solver.mjs';
import {fairLibraryEntry} from './horizon/library-entry-fairing.mjs';

const root=process.cwd(),target=resolve(root,'src/harbour/mountain/generated/library-landing.json');
const awningTarget=resolve(root,'src/harbour/mountain/generated/awning-landing.json');
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
// Read the authored branch before its generated heights are applied. This is local to this
// generator's module graph: no runtime environment switch or second browser geometry exists.
const server=await createServer({root,configFile:false,server:{middlewareMode:true},appType:'custom',optimizeDeps:{noDiscovery:true},
  plugins:[{name:'authored-library-landing',enforce:'pre',load(id){if(id===target||id===awningTarget)return 'null';}}]});
try{
  const {SKILL_BRANCHES,MOUNTAIN_COURSE_POINTS,MOUNTAIN_ROAD,courseIndexAt}=await server.ssrLoadModule('/src/harbour/mountain/course.ts');
  const {MOUNTAIN_ROAD_LINE}=await server.ssrLoadModule('/src/harbour/mountain/roads.ts');
  const {groundHeightAt}=await server.ssrLoadModule('/src/harbour/scene/ground.ts');
  const authored=SKILL_BRANCHES.find(b=>b.id==='library-balcony'),all=MOUNTAIN_ROAD_LINE.samples;
  const first=authored.points[0];
  const entryStation=all.reduce((a,b)=>Math.hypot(a.at[0]-first[0],a.at[2]-first[2])<Math.hypot(b.at[0]-first[0],b.at[2]-first[2])?a:b);
  // Use the actual native road stations, whose coarser corners are also used by
  // native support ownership; the fine design line can differ by nearly 9cm here.
  const entryRoad=MOUNTAIN_ROAD.map(at=>({at,s:all.reduce((a,b)=>Math.hypot(a.at[0]-at[0],a.at[2]-at[2])<Math.hypot(b.at[0]-at[0],b.at[2]-at[2])?a:b).s})).filter(p=>Math.abs(p.s-entryStation.s)<32);
  const entry=fairLibraryEntry(authored.landingRows,entryRoad,groundHeightAt);
  // Fair the entry before locking the roof for the terrain-constrained exit solve.
  if(JSON.stringify(entry.rows.slice(entry.preservedFromRow))!==JSON.stringify(authored.landingRows.slice(entry.preservedFromRow)))throw new Error('Entry fairing changed the protected roof or downstream geometry');
  const branch={...authored,points:entry.points,landingRows:entry.rows};
  const end=branch.points.at(-1);
  const exit=all.reduce((a,b)=>Math.hypot(a.at[0]-end[0],a.at[2]-end[2])<Math.hypot(b.at[0]-end[0],b.at[2]-end[2])?a:b);
  const road=all.filter(s=>Math.abs(s.s-exit.s)<32).map(({s,at})=>({s,at}));
  const lockedRows=branch.segments[0].points.length+branch.segments[1].points.length-1;
  const terrainSha256=hash(await readFile(resolve(root,'public/mountain/terrain/hearth-mountain-geo-2.bin')));
  const solverSha256=hash(await readFile(resolve(root,'scripts/horizon/library-landing-solver.mjs')));
  const entryFairingSha256=hash(await readFile(resolve(root,'scripts/horizon/library-entry-fairing.mjs')));
  const sourceSha256=hash(JSON.stringify({points:branch.points,rows:branch.landingRows,halfWidth:branch.halfWidth,lockedRows,entryRoad,road,terrainSha256,solverSha256,entryFairingSha256}));
  const result=generateLibraryLanding(branch,road,groundHeightAt,lockedRows);
  const payload={note:'Generated by scripts/generate-mountain-landings.mjs. One landing mesh for native and Horizon art, surface and collision. Do not edit by hand.',
    sourceSha256,terrainSha256,solverSha256,entryFairingSha256,entryPreservedFromRow:entry.preservedFromRow,lockedRows,...result};
  const text=JSON.stringify(payload)+'\n';
  if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==text)throw new Error('Stale library landing: run node scripts/generate-mountain-landings.mjs');}
  else await writeFile(target,text);
  console.log(JSON.stringify({bytes:text.length,sourceSha256,...result.diagnostics}));
  const {roadTagS}=await server.ssrLoadModule('/src/harbour/mountain/roadLine.ts');
  const {authorCurve}=await server.ssrLoadModule('/src/harbour/mountain/math.ts');
  const originalAwning=SKILL_BRANCHES.find(b=>b.id==='hearth-awning');
  const awningExit=courseIndexAt(roadTagS('hairpin-2')+2),targetEnd=MOUNTAIN_COURSE_POINTS[awningExit];
  const awning=awningReturnInput(originalAwning,targetEnd,authorCurve,groundHeightAt);
  const station=p=>all.reduce((a,b)=>Math.hypot(a.at[0]-p[0],a.at[2]-p[2])<Math.hypot(b.at[0]-p[0],b.at[2]-p[2])?a:b).s;
  const awningRoad=all.filter(p=>p.s>station(targetEnd)-22&&p.s<station(awning.points[0])+15).map(({s,at})=>({s,at}));
  const inputSha256=hash(await readFile(resolve(root,'scripts/horizon/awning-return-input.mjs')));
  const awningSolverSha256=hash(await readFile(resolve(root,'scripts/horizon/awning-return-solver.mjs')));
  // The portal margin exposes the baked Horizon field beside the native contour. Both
  // drawn grounds are lower bounds for this one shared deck; the actual portal stays open.
  const horizonTerrainBytes=await readFile(resolve(root,'public/horizon/terrain/horizon-geo-1.bin'));
  const horizonTerrainSha256=hash(horizonTerrainBytes);
  const {decodeTerrainAsset}=await server.ssrLoadModule('/src/harbour/horizon/land/terrain/asset.ts');
  const {sampleTerrain}=await server.ssrLoadModule('/src/harbour/horizon/land/terrain/index.ts');
  const {mouthExclusion,MOUTH_MARGIN}=await server.ssrLoadModule('/src/harbour/horizon/regions/mountainV2/geography.ts');
  const {MOUNTAIN_V2_OFFSET:offset}=await server.ssrLoadModule('/src/harbour/horizon/regions/mountainV2/placement.ts');
  const horizonWorld=JSON.parse(gunzipSync(await readFile(resolve(root,'public/horizon/world/horizon-geo-1.json.gz'))).toString());
  const mouths=horizonWorld.collision.mouths,excluded=mouthExclusion(mouths);
  const horizonField=decodeTerrainAsset(horizonTerrainBytes.buffer.slice(horizonTerrainBytes.byteOffset,horizonTerrainBytes.byteOffset+horizonTerrainBytes.byteLength),'full');
  const bothGrounds=(x,z)=>{const native=groundHeightAt(x,z);return excluded(x+offset.x,z+offset.z)?Math.max(native,sampleTerrain(horizonField,x+offset.x,z+offset.z)-offset.y):native;};
  const awningSourceSha256=hash(JSON.stringify({original:originalAwning.points,input:awning,exit:awningExit,road:awningRoad,terrainSha256,horizonTerrainSha256,mouths,margin:MOUTH_MARGIN,offset,inputSha256,awningSolverSha256}));
  const awningResult=generateAwningReturn(awning,awningRoad,bothGrounds,9);
  if(JSON.stringify(awningResult.points.slice(0,9))!==JSON.stringify(originalAwning.points.slice(0,9)))throw new Error('Awning return changed the protected entry or first rail');
  const awningPayload={note:'Generated by scripts/generate-mountain-landings.mjs. Shared native and Horizon contour return; original first rail preserved.',sourceSha256:awningSourceSha256,terrainSha256,horizonTerrainSha256,inputSha256,solverSha256:awningSolverSha256,exit:awningExit,lockedRows:9,...awningResult};
  const awningText=JSON.stringify(awningPayload)+'\n';
  if(process.argv.includes('--check')){if(await readFile(awningTarget,'utf8')!==awningText)throw new Error('Stale awning landing: run node scripts/generate-mountain-landings.mjs');}
  else await writeFile(awningTarget,awningText);
  console.log(JSON.stringify({awningBytes:awningText.length,sourceSha256:awningSourceSha256,...awningResult.diagnostics}));
}finally{await server.close();}
