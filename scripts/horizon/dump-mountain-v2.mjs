// Pass 5 (T1 Land): dump Mountain v2's authored geometry ONCE into Horizon space for the Horizon bake and manifest.
// v2's modules bake at import through top-level await (terrainBase fetches its asset), so they are loaded through Vite SSR the
// way scripts/generate-mountain-data.mjs does, never bundled into the Horizon bake. Output: src/harbour/horizon/land/mountainV2/v2-data.json
// (checked in; `--check` compares). horizon = native + MOUNTAIN_V2_OFFSET (regions/mountainV2/placement.ts).
import {createServer} from 'vite';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const root=process.cwd(),target=resolve(root,'src/harbour/horizon/land/mountainV2/v2-data.json');
const server=await createServer({root,configFile:false,server:{middlewareMode:true},appType:'custom',optimizeDeps:{noDiscovery:true}});
try {
  const load=p=>server.ssrLoadModule(p);
  const placement=await load('/src/harbour/horizon/regions/mountainV2/placement.ts');
  const places=await load('/src/harbour/mountain/places.ts');
  const course=await load('/src/harbour/mountain/course.ts');
  const roads=await load('/src/harbour/mountain/roads.ts');
  const planting=await load('/src/harbour/mountain/planting.ts');
  const transport=await load('/src/harbour/mountain/transport.ts');
  const dam=await load('/src/harbour/mountain/damParts.ts');
  const geo=await load('/src/harbour/horizon/regions/mountainV2/geography.ts');
  const paths=await load('/src/harbour/mountain/pathGraph.ts');
  const waterArt=await load('/src/harbour/mountain/art/damArt.ts');
  const O=placement.MOUNTAIN_V2_OFFSET,r=v=>Math.round(v*100)/100;
  const H=p=>[r(p[0]+O.x),r(p[1]+O.y),r(p[2]+O.z)],HXZ=p=>[r(p[0]+O.x),r(p[1]+O.z)];
  const road=roads.MOUNTAIN_ROAD_LINE.samples;
  const precise=p=>[p[0]+O.x,p[1]+O.y,p[2]+O.z].map(v=>Math.round(v*1e6)/1e6);
  let planS=0;
  const gondola=transport.GONDOLA_LINE,funicular=transport.FUNICULAR_LINE;
  // A tower's top is the cable path's height at the tower (the path passes each support exactly).
  const towerTop=t=>{let best=gondola.path[0],d=Infinity;for(const p of gondola.path){const e=Math.hypot(p[0]-t[0],p[2]-t[2]);if(e<d){d=e;best=p;}}return best[1];};
  const payload={
    note:'Generated by scripts/horizon/dump-mountain-v2.mjs from src/harbour/mountain/** (Mountain v2, hearth-mountain-geo-2). Horizon space: native + offset. Do not edit by hand.',
    offset:O,revision:places.GEOGRAPHY_REVISION,
    road:{id:roads.MOUNTAIN_ROAD_LINE.id,length:r(roads.MOUNTAIN_ROAD_LINE.length),foot:H(road[0].at),top:H(road.at(-1).at),
      // Preserve the drawn centreline and its widths. Decimation chords cut hairpins
      // and make a correctly placed native edge guard appear inside the carriageway.
      samples:road.map(s=>({s:s.s,at:precise(s.at),normal:s.normal.map(n=>Math.round(n*1e9)/1e9),hw:s.halfWidth,support:s.support,bridge:s.bridgeId??null})),
      // Curvature is a raw float whose last ulp differs between x64 and arm64 (CI Linux vs macOS); round it like the normals so --check is portable.
      frames:road.map((s,i)=>{if(i)planS+=Math.hypot(s.at[0]-road[i-1].at[0],s.at[2]-road[i-1].at[2]);return {s:planS,spatialS:s.s,at:precise(s.at),half:s.halfWidth,grade:s.grade,curvature:Math.round(s.curvature*1e9)/1e9,left:s.left,right:s.right,bridge:s.bridgeId};}),
      bridges:roads.GORGE_BRIDGES.filter(b=>b.carries==='road').map(b=>({id:`mountainV2:${b.id}`,name:b.name,axis:b.deck.map(precise),width:b.halfWidth*2})),
      guards:roads.EDGE_RUNS.filter(e=>e.line==='mountain-road').map(e=>({...e,points:e.points.map(precise)})),
      openings:roads.EDGE_OPENINGS.filter(e=>e.line==='mountain-road').map(e=>({...e,corridor:e.corridor.map(precise)})),
      planting:planting.mountainTrees('full').filter(t=>road.some(s=>Math.hypot(t.x-s.at[0],t.z-s.at[2])<30)).map(t=>({at:precise([t.x,t.y,t.z]),...planting.crownOf(t)}))},
    nativePlanning:{
      solids:geo.REGION_SOLIDS.map(s=>({id:s.id,min:precise(s.min),max:precise(s.max)})),
      buildings:Object.entries(places.BUILDING_SITES).map(([id,p])=>({id,at:HXZ(p),half:places.BUILDING_FORMS[id].half,yaw:places.buildingYaw(p)})),
      walks:paths.PATH_EDGES.map(p=>({id:p.id,kind:p.kind,halfWidth:p.halfWidth,points:p.points.map(precise)})),
      surfaces:geo.REGION_SURFACES.map(s=>({id:s.id,kind:s.kind,halfWidth:s.halfWidth,points:s.points.map(precise)})),
      trees:planting.mountainTrees('full').map(t=>({at:precise([t.x,t.y,t.z]),...planting.crownOf(t)})),
      reservoir:{level:places.RESERVOIR_LEVEL_MAX+O.y,outline:waterArt.reservoirOutline(places.RESERVOIR_LEVEL_MAX).map(p=>[p[0]+O.x,p[1]+O.z])},
    },
    course:{points:course.MOUNTAIN_COURSE_POINTS.map(H),length:r(course.MOUNTAIN_COURSE_LENGTH),
      segments:course.MOUNTAIN_RACE_SEGMENTS.map(s=>({id:s.id,name:s.name,i0:s.i0,i1:s.i1,s0:r(s.s0),s1:r(s.s1)})),
      gates:course.MOUNTAIN_GATES.map(g=>({id:g.id,name:g.name,segment:g.segment,at:H(g.at),normal:g.normal.map(r),halfWidth:g.halfWidth})),
      finish:{at:H(course.RACE_FINISH.at),heading:course.RACE_FINISH.heading.map(v=>Math.round(v*1e4)/1e4),runout:r(course.RACE_FINISH.runout)}},
    gondola:{stations:gondola.stations.map(s=>({id:s.id,name:s.name,at:H(s.at),platform:H(s.platform.at),yaw:Math.round(s.platform.yaw*1e4)/1e4})),
      towers:gondola.towers.map(t=>({ground:H(t),top:r(towerTop(t)+O.y)})),length:r(gondola.length)},
    funicular:{stations:funicular.stations.map(s=>({id:s.id,name:s.name,at:H(s.at),platform:H(s.platform.at),yaw:Math.round(s.platform.yaw*1e4)/1e4})),length:r(funicular.length)},
    dam:{centre:H(places.DAM.centre),crest:r(places.DAM.crest+O.y),foot:r(places.DAM.foot+O.y),radius:places.DAM.radius,halfAngle:places.DAM.halfAngle,
      promenade:dam.DAM_PARTS.promenade.map(H),arc:dam.DAM_PARTS.arc.map(H),apron:{at:H(dam.DAM_PARTS.apron.at),half:dam.DAM_PARTS.apron.half},
      abutments:dam.DAM_PARTS.abutments.map(a=>({side:a.side,at:H(a.at),size:a.size})),
      kittyChambers:dam.KITTY_CHAMBERS.map(k=>({id:k.id,at:H(k.at),radius:k.radius,depth:k.depth})),
      reservoir:{level:r(dam.RESERVOIR.level+O.y),bottom:r(dam.RESERVOIR.bottom+O.y),shore:dam.RESERVOIR.shore.map(p=>HXZ([p[0],p[2]]))}},
    river:{points:places.RIVER.map(H),halfWidth:places.RIVER_HALF_WIDTH},
    observatory:{at:H(places.SUMMIT_OBSERVATORY_SITE.at),radius:places.SUMMIT_OBSERVATORY_SITE.radius},
    pavilion:{at:H(places.GOAL_PAVILION_SITE.at),half:places.GOAL_PAVILION_SITE.half},
    buildingSites:Object.fromEntries(Object.entries(places.BUILDING_SITES).map(([k,v])=>[k,HXZ(v)])),
    reservedPlots:places.RESERVED_PLOTS.map(p=>({id:p.id,name:p.name,at:H(p.at),half:p.half})),
    terraces:places.TERRACES.map(t=>({id:t.id,at:H(t.at),radii:t.radii,yaw:t.yaw,bank:t.bank})),
  };
  const text=JSON.stringify(payload)+'\n';
  if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==text)throw new Error('Stale v2-data.json: run node scripts/horizon/dump-mountain-v2.mjs');}
  else{await mkdir(resolve(target,'..'),{recursive:true});await writeFile(target,text);}
  console.log('mountainV2 data',target,text.length,'bytes; road samples',payload.road.samples.length,'course points',payload.course.points.length);
} finally {await server.close();}
